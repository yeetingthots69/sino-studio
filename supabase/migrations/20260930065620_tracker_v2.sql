create function public.tracker_normalize_cut(raw text) returns text
language sql immutable set search_path = '' as $$
  select regexp_replace(upper(regexp_replace(raw, '\s', '', 'g')), '^C0+(?=[0-9])', 'C')
$$;  -- TS mirror normalizeCutCode must match (fixture test)
revoke execute on function public.tracker_normalize_cut(text) from anon, public;
grant execute on function public.tracker_normalize_cut(text) to authenticated, service_role;

-- (1) pre-backfill asserts ----------------------------------------------------------------------------
do $$
begin
  if (select count(*) from public.tracker_projects) <> 1 then
    raise exception 'tracker_v2 pre-assert: expected exactly 1 project';
  end if;
  if (select count(*) from public.tracker_work_types) <> 3
     or (select count(*) from public.tracker_work_types where code in ('LO','GE','DO + SH') and archived_at is null) <> 3 then
    raise exception 'tracker_v2 pre-assert: expected work types LO, GE, DO + SH, none archived';
  end if;
  if exists (select 1 from public.tracker_tasks where project_id <> (select id from public.tracker_projects)) then
    raise exception 'tracker_v2 pre-assert: task outside the single project';
  end if;
  if exists (select 1 from public.tracker_tasks
             where length(public.tracker_normalize_cut(name)) not between 1 and 20) then
    raise exception 'tracker_v2 pre-assert: normalised task name length outside 1..20';
  end if;
  if exists (select 1 from public.tracker_tasks
             group by public.tracker_normalize_cut(name), work_type_id having count(*) > 1) then
    raise exception 'tracker_v2 pre-assert: two tasks share (cut, work type)';
  end if;
end $$;

