-- Every rule trigger / RPC starts with the inline project lock:
--   perform pg_advisory_xact_lock(hashtextextended(<project_id>::text, 0));

-- 1. pipeline order rule (C1/C2): every insert and update
create function private.tracker_task_order() returns trigger
language plpgsql security invoker set search_path = '' as $$
declare
  v_order int;
  v_conflict uuid;
begin
  if tg_op = 'UPDATE' and new.project_id is distinct from old.project_id then
    raise exception using errcode = 'P0001', message = 'project_immutable';
  end if;
  perform pg_advisory_xact_lock(hashtextextended(new.project_id::text, 0));
  select sort_order into v_order from public.tracker_work_types where id = new.work_type_id;
  if v_order is null then
    return new;  -- unknown type: the FK reports it
  end if;
  select t.id into v_conflict
  from public.tracker_tasks t
  join public.tracker_work_types w on w.id = t.work_type_id
  where t.cut_id = new.cut_id and t.id <> new.id
    and ((w.sort_order < v_order and t.end_date >= new.start_date)
      or (w.sort_order > v_order and t.start_date <= new.end_date))
  order by w.sort_order
  limit 1;
  if v_conflict is not null then
    raise exception using errcode = 'P0001', message = 'order_conflict', detail = v_conflict::text;
  end if;
  return new;
end $$;
create trigger tracker_task_order before insert or update on public.tracker_tasks
  for each row execute function private.tracker_task_order();

