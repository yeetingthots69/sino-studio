-- RPCs (SECURITY INVOKER; RLS applies) ----------------------------------------------------------------
create function public.tracker_create_project(p_name text, p_color text, p_types jsonb)
returns public.tracker_projects
language plpgsql security invoker set search_path = '' as $$
declare
  v_project public.tracker_projects;
begin
  insert into public.tracker_projects (name, color) values (p_name, p_color) returning * into v_project;
  perform pg_advisory_xact_lock(hashtextextended(v_project.id::text, 0));
  insert into public.tracker_work_types (project_id, code, label, color, pay_pct, sort_order)
  select v_project.id, e.code, e.label, e.color, e.pay_pct, e.sort_order
  from jsonb_to_recordset(p_types) as e(code text, label text, color text, pay_pct numeric, sort_order int);
  return v_project;
end $$;

create function public.tracker_save_work_types(p_project uuid, p_types jsonb)
returns setof public.tracker_work_types
language plpgsql security invoker set search_path = '' as $$
begin
  perform pg_advisory_xact_lock(hashtextextended(p_project::text, 0));
  delete from public.tracker_work_types w
  where w.project_id = p_project
    and not exists (select 1 from jsonb_array_elements(p_types) e where (e ->> 'id')::uuid = w.id);
  update public.tracker_work_types w set
    code = e.code, label = e.label, color = e.color, pay_pct = e.pay_pct, sort_order = e.sort_order
  from jsonb_to_recordset(p_types) as e(id uuid, code text, label text, color text, pay_pct numeric, sort_order int)
  where e.id is not null and w.id = e.id and w.project_id = p_project;
  insert into public.tracker_work_types (project_id, code, label, color, pay_pct, sort_order)
  select p_project, e.code, e.label, e.color, e.pay_pct, e.sort_order
  from jsonb_to_recordset(p_types) as e(id uuid, code text, label text, color text, pay_pct numeric, sort_order int)
  where e.id is null;
  return query select * from public.tracker_work_types where project_id = p_project order by sort_order;
end $$;

create function public.tracker_create_task(p_project uuid, p_staff uuid, p_type uuid, p_cut_code text,
                                           p_start date, p_end date, p_budget bigint default null)
returns jsonb
language plpgsql security invoker set search_path = '' as $$
declare
  v_code text := public.tracker_normalize_cut(p_cut_code);
  v_cut public.tracker_cuts;
  v_task public.tracker_tasks;
begin
  perform pg_advisory_xact_lock(hashtextextended(p_project::text, 0));
  insert into public.tracker_cuts (project_id, code, budget)
  values (p_project, v_code, coalesce(p_budget, 0))
  on conflict (project_id, code) do nothing;
  select * into v_cut from public.tracker_cuts where project_id = p_project and code = v_code;
  insert into public.tracker_tasks (project_id, staff_id, work_type_id, cut_id, start_date, end_date)
  values (p_project, p_staff, p_type, v_cut.id, p_start, p_end)
  returning * into v_task;
  return jsonb_build_object('task', to_jsonb(v_task), 'cut', to_jsonb(v_cut));
end $$;

create function public.tracker_ensure_cut(p_project uuid, p_code text)
returns public.tracker_cuts
language plpgsql security invoker set search_path = '' as $$
declare
  v_code text := public.tracker_normalize_cut(p_code);
  v_cut public.tracker_cuts;
begin
  perform pg_advisory_xact_lock(hashtextextended(p_project::text, 0));
  insert into public.tracker_cuts (project_id, code) values (p_project, v_code)
  on conflict (project_id, code) do nothing;
  select * into v_cut from public.tracker_cuts where project_id = p_project and code = v_code;
  return v_cut;
end $$;

create function public.tracker_add_adjustments(p_batch uuid, p_project uuid, p_reason text, p_entries jsonb)
returns setof public.tracker_pay_adjustments
language plpgsql security invoker set search_path = '' as $$
declare
  v_inserted int;
begin
  perform pg_advisory_xact_lock(hashtextextended(p_project::text, 0));
  insert into public.tracker_adjustment_batches (id, project_id, reason)
  values (p_batch, p_project, p_reason)
  on conflict (id) do nothing;
  get diagnostics v_inserted = row_count;
  if v_inserted = 0 then
    return query select * from public.tracker_pay_adjustments where batch_id = p_batch order by created_at, id;
    return;
  end if;
  return query
  with ins as (
    insert into public.tracker_pay_adjustments
      (batch_id, project_id, cut_id, work_type_id, staff_id, amount, reason, reverses_id)
    select p_batch, p_project, e.cut_id, e.work_type_id, e.staff_id, e.amount,
           coalesce(e.reason, p_reason), e.reverses_id
    from jsonb_to_recordset(p_entries)
      as e(cut_id uuid, work_type_id uuid, staff_id uuid, amount bigint, reason text, reverses_id uuid)
    returning *
  )
  select * from ins;
end $$;

-- Claim RPCs (service role only; email worker)
create function public.tracker_claim_notices(p_limit int, p_lease interval)
returns setof public.tracker_notice_queue
language sql security invoker set search_path = '' as $$
  update public.tracker_notice_queue set claimed_until = now() + p_lease
  where staff_id in (
    select staff_id from public.tracker_notice_queue
    where due_at <= now() and (claimed_until is null or claimed_until < now())
    order by due_at
    for update skip locked
    limit p_limit)
  returning *;
$$;

create function public.tracker_claim_emails(p_limit int, p_lease interval)
returns setof public.tracker_email_log
language sql security invoker set search_path = '' as $$
  update public.tracker_email_log set
    claim_token = gen_random_uuid(), claimed_until = now() + p_lease, attempts = attempts + 1
  where id in (
    select id from public.tracker_email_log
    where status in ('pending','failed') and attempts < 5
      and created_at > now() - interval '23 hours'
      and (claimed_until is null or claimed_until < now())
    order by created_at
    for update skip locked
    limit p_limit)
  returning *;
$$;

