-- 3. work-type guard: project immutable; used types cannot be reordered or deleted
create function private.tracker_type_guard() returns trigger
language plpgsql security invoker set search_path = '' as $$
begin
  if tg_op = 'INSERT' then
    perform pg_advisory_xact_lock(hashtextextended(new.project_id::text, 0));
    return new;
  end if;
  perform pg_advisory_xact_lock(hashtextextended(old.project_id::text, 0));
  if tg_op = 'UPDATE' then
    if new.project_id is distinct from old.project_id then
      raise exception using errcode = 'P0001', message = 'project_immutable';
    end if;
    if old.sort_order is distinct from new.sort_order
       and exists (select 1 from public.tracker_tasks where work_type_id = old.id) then
      raise exception using errcode = 'P0001', message = 'type_in_use';
    end if;
    return new;
  end if;
  if exists (select 1 from public.tracker_tasks where work_type_id = old.id) then
    raise exception using errcode = 'P0001', message = 'type_in_use';
  end if;
  return old;
end $$;
create trigger tracker_type_guard before insert or update or delete on public.tracker_work_types
  for each row execute function private.tracker_type_guard();

-- 4. pay % total = 100 and >= 1 type, checked at commit
create function private.tracker_pct_total() returns trigger
language plpgsql security invoker set search_path = '' as $$
declare
  v_project uuid;
  v_count int;
  v_sum numeric;
begin
  if tg_table_name = 'tracker_projects' then
    v_project := new.id;
  elsif tg_op = 'DELETE' then
    v_project := old.project_id;
  else
    v_project := new.project_id;
  end if;
  perform pg_advisory_xact_lock(hashtextextended(v_project::text, 0));
  if not exists (select 1 from public.tracker_projects where id = v_project) then
    return null;
  end if;
  select count(*), coalesce(sum(pay_pct), 0) into v_count, v_sum
  from public.tracker_work_types where project_id = v_project;
  if v_count < 1 or v_sum <> 100 then
    raise exception using errcode = 'P0001', message = 'pct_total';
  end if;
  return null;
end $$;
create constraint trigger tracker_pct_total after insert or update or delete on public.tracker_work_types
  deferrable initially deferred for each row execute function private.tracker_pct_total();
create constraint trigger tracker_pct_total after insert on public.tracker_projects
  deferrable initially deferred for each row execute function private.tracker_pct_total();

-- 5. adjustments: actor stamp + reversal rules
create function private.tracker_adjustment_guard() returns trigger
language plpgsql security invoker set search_path = '' as $$
declare
  v_orig public.tracker_pay_adjustments;
begin
  perform pg_advisory_xact_lock(hashtextextended(new.project_id::text, 0));
  new.created_by := lower((select auth.jwt()) ->> 'email');
  if new.created_by is null then
    raise exception using errcode = 'P0001', message = 'adjustment_invalid';
  end if;
  if (select project_id from public.tracker_adjustment_batches where id = new.batch_id) is distinct from new.project_id then
    raise exception using errcode = 'P0001', message = 'adjustment_invalid';
  end if;
  if new.reverses_id is null then
    if not exists (select 1 from public.tracker_staff where id = new.staff_id and archived_at is null) then
      raise exception using errcode = 'P0001', message = 'adjustment_invalid';
    end if;
  else
    select * into v_orig from public.tracker_pay_adjustments where id = new.reverses_id;
    if not found
       or v_orig.reverses_id is not null
       or (v_orig.project_id, v_orig.cut_id, v_orig.work_type_id, v_orig.staff_id)
          is distinct from (new.project_id, new.cut_id, new.work_type_id, new.staff_id)
       or new.amount <> -v_orig.amount then
      raise exception using errcode = 'P0001', message = 'adjustment_invalid';
    end if;
  end if;
  return new;
end $$;
create trigger tracker_adjustment_guard before insert on public.tracker_pay_adjustments
  for each row execute function private.tracker_adjustment_guard();

