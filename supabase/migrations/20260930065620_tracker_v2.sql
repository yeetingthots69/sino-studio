-- 8. assignment-notice outbox (definer: users cannot write the queue)
create function private.tracker_enqueue_notice() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.tracker_notice_queue (staff_id, task_ids, due_at)
  values (new.staff_id, array[new.id], now() + interval '10 minutes')
  on conflict (staff_id) do update set
    due_at = excluded.due_at,
    generation = public.tracker_notice_queue.generation + 1,
    task_ids = (select array_agg(distinct x) from unnest(public.tracker_notice_queue.task_ids || new.id) x),
    claimed_until = null;
  return null;
end $$;
create trigger tracker_enqueue_notice_ins after insert on public.tracker_tasks
  for each row execute function private.tracker_enqueue_notice();
create trigger tracker_enqueue_notice_upd after update on public.tracker_tasks
  for each row when ((old.staff_id, old.start_date, old.end_date, old.cut_id, old.work_type_id)
                     is distinct from (new.staff_id, new.start_date, new.end_date, new.cut_id, new.work_type_id))
  execute function private.tracker_enqueue_notice();

