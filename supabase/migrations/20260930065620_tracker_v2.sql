-- 7. audit (definer: writes the audit table users cannot write)
create function private.tracker_audit() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.tracker_audit_log (actor, table_name, row_id, action, old, new)
  values (
    lower((select auth.jwt()) ->> 'email'),
    tg_table_name,
    case when tg_op = 'DELETE' then old.id else new.id end,
    lower(tg_op),
    case when tg_op = 'INSERT' then null else to_jsonb(old) end,
    case when tg_op = 'DELETE' then null else to_jsonb(new) end
  );
  return null;
end $$;
create trigger tracker_audit_ins after insert on public.tracker_cuts
  for each row execute function private.tracker_audit();
